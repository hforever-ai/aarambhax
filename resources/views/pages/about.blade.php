            <p>Aarambhax Legal is a drafting tool built for working Indian advocates — starting with Chhattisgarh.</p>

            <h2>Why we built it</h2>
            <p>Most legal AI tools today fail Indian advocates in three specific ways: they don't speak Hindi, they don't understand Revenue Courts, and they lose context the moment you try to edit a draft. Aarambhax fixes all three.</p>

            <h2>Who it's for</h2>
            <p>Practising advocates handling matters at the Chhattisgarh High Court (Bilaspur), district and sessions courts, and revenue courts (Tehsildar / SDO / Collector / Commissioner / Board of Revenue). Generic Indian advocates outside CG can use it too, but the polish is CG-first.</p>

            <h2>What's different</h2>
            <ul>
                <li><strong>Hindi-native.</strong> Devanagari output, vakeel-grade legal Hindi register, district court conventions baked in.</li>
                <li><strong>Revenue-aware.</strong> Naamantaran, batwara, vyapvartan, atikraman with khasra/khata structure — the only product that does this.</li>
                <li><strong>Verifier.</strong> Every cited section and judgment is checked against the actual statute and Indian Kanoon. Green / amber / red badges.</li>
                <li><strong>Edit by chat.</strong> AI keeps full memory of your case facts. Tell it "tighten paragraph 3" or "add a ground about delay" — it edits without forgetting anything.</li>
            </ul>

            <h2>Honest disclaimer</h2>
            <p>Every Aarambhax-generated draft is reviewed by you before filing. AI-generated legal text can contain mistakes — that's why the Verifier exists, and why every export carries a clear notice. Aarambhax is a drafting accelerator, not a substitute for advocate judgment.</p>
